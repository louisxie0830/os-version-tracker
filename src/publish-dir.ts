import { randomBytes } from 'node:crypto';
import { existsSync, readdirSync, statSync } from 'node:fs';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { BUILD_MARKER, resolveOutputDir } from './output-dir.js';

/**
 * Builds the static site in a staging directory and only then puts it in place of the output directory, so
 * a build that fails halfway (a render error, a full disk) leaves the previous site complete.
 *
 * The staging directory is a sibling of the output directory (".site.staging-<pid>-<start ms>-<random>"): the same file
 * system, so the final move is a rename, and it passes the same safety checks (resolveOutputDir) as the
 * output directory itself. Nothing is ever deleted except directories this module created (staging, backup).
 *
 * Replacing: neither POSIX nor Windows can rename a directory over an existing non-empty one, and there's no
 * portable atomic swap of two directories. So the old directory is first renamed aside (".site.backup-…"),
 * the new one renamed into place, and the backup removed. If the second rename fails, the backup is renamed
 * back, so a failed swap never leaves the site missing. Between the two renames (microseconds) the output
 * directory doesn't exist; a crash exactly then leaves the backup behind, and the next build restores it
 * before doing anything else (recoverInterrupted). The name is the lease: which process made the directory
 * and when. A leftover is only treated as a build still in progress while that process is alive AND the
 * lease is younger than STALE_AFTER_MS (well over the 15-minute build job limit), so a reused PID can't keep
 * an old directory around for good. On Windows a rename can fail for a moment while another
 * program (an indexer, antivirus) has a file open, so renames are retried briefly.
 */

/** File operations used, injectable so tests can make the swap fail */
export interface DirOps {
  rename: (from: string, to: string) => Promise<void>;
  rm: (target: string, options: { recursive: true; force: true }) => Promise<void>;
}
const nodeOps: DirOps = { rename, rm };

const MARKER_TEXT = 'Generated by os-version-tracker build-static; safe to delete.\n';
const stagingPrefix = (out: string) => `.${path.basename(out)}.staging-`;
const backupPrefix = (out: string) => `.${path.basename(out)}.backup-`;

/** Rename, retried briefly for the transient errors Windows gives while another program has a file open */
async function renameWithRetry(ops: DirOps, from: string, to: string): Promise<void> {
  for (let attempt = 0; ; attempt++) {
    try {
      return await ops.rename(from, to);
    } catch (err) {
      const code = (err as NodeJS.ErrnoException).code;
      if (attempt >= 3 || !(code === 'EPERM' || code === 'EBUSY' || code === 'EACCES')) throw err;
      await new Promise(r => setTimeout(r, 100 * (attempt + 1)));
    }
  }
}

/** A lease older than this is stale whatever its PID: the build job is cut off after 15 minutes */
export const STALE_AFTER_MS = 60 * 60 * 1000;

const isAlive = (pid: number): boolean => {
  try {
    process.kill(pid, 0);
    return true;
  } catch (err) {
    return (err as NodeJS.ErrnoException).code === 'EPERM'; // exists, owned by someone else
  }
};

/**
 * The lease in a leftover's name: "<pid>-<start ms>-<random>". Directories named by older versions
 * ("<pid>-<random>") have no start time; their modification time stands in for it.
 */
function leaseOf(name: string, prefix: string, full: string): { pid: number; startedAt: number } {
  const id = name.slice(prefix.length);
  const lease = id.match(/^(\d+)-(\d+)-[0-9a-f]+$/);
  if (lease) return { pid: Number(lease[1]), startedAt: Number(lease[2]) };
  return { pid: Number(id.split('-')[0]), startedAt: statSync(full).mtimeMs };
}

/**
 * Whether a leftover belongs to a build that is still in progress: its process is alive (and isn't this one)
 * and its lease is fresh. A lease from the future beyond the threshold (a wrong clock) counts as stale too.
 */
function inProgress(lease: { pid: number; startedAt: number }, now: number, alive: (pid: number) => boolean): boolean {
  if (!Number.isInteger(lease.pid) || lease.pid <= 0 || lease.pid === process.pid) return false;
  if (!(Math.abs(now - lease.startedAt) < STALE_AFTER_MS)) return false;
  return alive(lease.pid);
}

/** Ours: it has the build marker, or it's empty (made by us and interrupted before anything was written) */
const isOurs = (dir: string) => existsSync(path.join(dir, BUILD_MARKER)) || readdirSync(dir).length === 0;

/**
 * Leftovers of an interrupted build next to the output directory: a backup is put back when the output
 * directory is missing (the crash came between the two renames), otherwise removed; stale staging
 * directories are removed. Only directories with our marker (or empty), and never those of a build that
 * is still in progress (see inProgress). `now` and `alive` are injectable for tests.
 */
export async function recoverInterrupted(out: string, ops: DirOps = nodeOps, now = Date.now(), alive: (pid: number) => boolean = isAlive): Promise<string[]> {
  const parent = path.dirname(out);
  if (!existsSync(parent)) return [];
  const done: string[] = [];
  const leftovers = readdirSync(parent)
    .filter(name => name.startsWith(backupPrefix(out)) || name.startsWith(stagingPrefix(out)))
    .map(name => ({ name, full: path.join(parent, name), backup: name.startsWith(backupPrefix(out)) }))
    .filter(l => statSync(l.full).isDirectory() && isOurs(l.full) && !inProgress(leaseOf(l.name, l.backup ? backupPrefix(out) : stagingPrefix(out), l.full), now, alive))
    // Newest backup first, in case there is more than one
    .sort((a, b) => statSync(b.full).mtimeMs - statSync(a.full).mtimeMs);
  for (const l of leftovers) {
    if (l.backup && !existsSync(out)) {
      await renameWithRetry(ops, l.full, out);
      done.push(`restored ${out} from ${l.name}`);
    } else {
      await ops.rm(l.full, { recursive: true, force: true });
      done.push(`removed ${l.name}`);
    }
  }
  return done;
}

/** Fails unless each file exists in `dir` and isn't empty */
export function requireFiles(dir: string, files: readonly string[]): void {
  const missing = files.filter(f => {
    const file = path.join(dir, f);
    return !existsSync(file) || statSync(file).size === 0;
  });
  if (missing.length) throw new Error(`The built site is incomplete (missing or empty: ${missing.join(', ')}); the previous site was left in place`);
}

/**
 * Writes a new output directory with `write`, checks it with `verify`, and puts it in place of `outDir`
 * (see the notes above). On any failure the staging directory is removed and the previous output directory
 * is left as it was. Returns the resolved output directory.
 */
export async function buildIntoDirectory(
  outDir: string,
  root: string,
  write: (dir: string) => Promise<void>,
  options: { verify?: (dir: string) => void | Promise<void>; ops?: DirOps; cwd?: string } = {},
): Promise<string> {
  const ops = options.ops ?? nodeOps;
  const out = resolveOutputDir(outDir, root, options.cwd);
  for (const line of await recoverInterrupted(out, ops)) console.warn(`[build] interrupted earlier build: ${line}`);
  // The lease (see inProgress): this process, and when it started writing
  const id = `${process.pid}-${Date.now()}-${randomBytes(4).toString('hex')}`;
  const staging = path.join(path.dirname(out), `${stagingPrefix(out)}${id}`);
  const backup = path.join(path.dirname(out), `${backupPrefix(out)}${id}`);
  // The staging directory gets the same checks as the output directory (inside the repository or the temp
  // directory, clear of protected folders), and must not exist yet: mkdir without recursive refuses one that does
  resolveOutputDir(staging, root, options.cwd);
  await mkdir(path.dirname(out), { recursive: true });
  await mkdir(staging);
  try {
    // Marks the directory as ours, so a later build may safely replace it
    await writeFile(path.join(staging, BUILD_MARKER), MARKER_TEXT);
    await write(staging);
    await options.verify?.(staging);
    // Re-check right before replacing: the output directory may have changed while the site was written
    resolveOutputDir(out, root, options.cwd);
    if (existsSync(out)) {
      await renameWithRetry(ops, out, backup);
      try {
        await renameWithRetry(ops, staging, out);
      } catch (err) {
        // Put the previous site back; if even that fails, the next build restores it from the backup
        await renameWithRetry(ops, backup, out).catch(restoreErr => {
          console.error(`[build] could not put ${out} back (${(restoreErr as Error).message}); the next build restores it from ${backup}`);
        });
        throw err;
      }
      await ops.rm(backup, { recursive: true, force: true }).catch(err => {
        console.warn(`[build] could not remove ${backup} (${(err as Error).message}); the next build removes it`);
      });
    } else {
      await renameWithRetry(ops, staging, out);
    }
  } catch (err) {
    await ops.rm(staging, { recursive: true, force: true }).catch(() => {});
    throw err;
  }
  return out;
}
